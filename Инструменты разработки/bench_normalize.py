def clean(s: str) -> str:
    s = s.lower().replace("ё", "е").replace("+", "").replace("́", "")
    s = re.sub(r"[-–—]", " ", s)
    s = re.sub(r"[^\w ]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def runner_ours():
    from core.normalize import normalize_text
    return lambda t: normalize_text(t, language="ru")


def runner_rnz(**opts):
    import ru_normalizr as R
    o = R.NormalizeOptions(**opts) if opts else None
    return lambda t: R.normalize(t, o)


def runner_runorm():
    from runorm import RUNorm
    n = RUNorm()
    n.load(model_size="small", device="cpu")
    return n.norm


def main() -> int:
    systems = [("наш normalize.py", runner_ours),
               ("ru-normalizr (по умолчанию)", runner_rnz),
               ("ru-normalizr + буквы и инициалы", lambda: runner_rnz(
                   enable_letter_abbreviation_expansion=True, enable_initials_expansion=True)),
               ("RUNorm small", runner_runorm)]
    rows = []
    for name, mk in systems:
        try:
            fn = mk()
        except Exception as e:
            print(f"{name}: не загрузился ({e})")
            continue
        ok, bad, t0 = 0, [], time.time()
        for src, want in CASES:
            try:
                got = fn(src)
            except Exception as e:
                got = f"<сбой {e}>"
            if clean(got) == clean(want):
                ok += 1
            else:
                bad.append((src, got))
        rows.append((name, ok, round(time.time() - t0, 1), bad))
        print(f"{name}: {ok}/{len(CASES)} за {rows[-1][2]} с")
    for name, ok, t, bad in rows:
        print(f"\n== {name}: ошибки ({len(bad)})")
        for s, g in bad:
            print(f"   {s}  ->  {g}")
    return 0


