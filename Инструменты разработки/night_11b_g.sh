#!/bin/zsh
# Задание 11б, решение Андрея 22.10 10:24 - ночная цепочка Герасимова:
#  1) полное дообучение F5 на «Олесе» (эпохи, лучшая по отложенным фразам);
#  2) короткий набор «Точка Д»: абзац - образец «Олеся» / образец «К» / «К» + DFN (лучший у Андрея
#     по пробе), к ним - «F5 как сейчас», проба «К + DFN» и живой (из «Точки В3»); замер;
#  3) длинный кусок теми же тремя; замер;
#  4) голос в программе «Вячеслав Герасимов (F5, обучен)» - образец «К» + DFN (выбор Андрея по пробе);
#  5) тесты ударений: test_stress (текст), stress_steps_11a итог (50 + 300 слов по тексту),
#     50 трудных слов по звуку обученными F5 (stress50_f5_11b.py);
#  6) замок. Замок взят заранее живым процессом (lock_take.sh) - здесь только освобождается.
# Журнал - Архив/11б/ночь Герасимов.log.
#   zsh "Инструменты разработки/night_11b_g.sh"
cd "$(dirname "$0")/.."
LOG="Архив/11б/ночь Герасимов.log"
T="Инструменты разработки"
R="Вячеслав Герасимов"
G="$HOME/.cache/text2audio/train/$R"
W="$G/f5-lora-full"
D="Сравнение 3.10 - лучшие варианты/Точка Д - Герасимов обучен"
V3="Сравнение 3.10 - лучшие варианты/Точка В3"
L="Сравнение 3.9 - голоса диктора на выбор/Длинный кусок"
say() { echo "$(date +%H:%M:%S) $*" | tee -a "$LOG"; }
trap 'zsh "$T/lock_free.sh" >> "$LOG" 2>&1' EXIT
grep -q "^Herald" ../.heavy-lock/owner 2>/dev/null || { say "замок не наш - стоп"; exit 1; }

say "обучение F5, Герасимов («Олеся»)"
caffeinate -i .venv/bin/python "$T/f5_finetune_11b.py" --voice "$R" --epochs 8 --frames 900 \
  --lr 1e-4 --data train_olesya_dfn.jsonl --out f5-lora-full 2>&1 | grep -a "эпоха\|фраз\|готово\|Error\|Traceback" >> "$LOG"
[ -f "$W/model_v1.safetensors" ] || { say "весов нет - стоп"; exit 1; }

say "голоса для набора"
.venv/bin/python "$T/install_f5_trained_11b.py" "$R" "$W" --ref "$R (Олеся)" --name "$R (F5, обучен, образец Олеся)" >> "$LOG"
.venv/bin/python "$T/install_f5_trained_11b.py" "$R" "$W" --name "$R (F5, обучен, образец К)" >> "$LOG"
.venv/bin/python "$T/install_f5_trained_11b.py" "$R" "$W" --name "$R (F5, обучен)" --denoise 100 >> "$LOG"

say "короткий набор (абзац)"
F="Точка Д - Герасимов обучен"
.venv/bin/python "$T/paragraph_11b.py" "$F" main "$R (F5, обучен, образец Олеся)" "Герасимов - обучен + образец Олеся" 2>&1 | grep -a "mp3\|Error\|Traceback" >> "$LOG"
.venv/bin/python "$T/paragraph_11b.py" "$F" main "$R (F5, обучен, образец К)" "Герасимов - обучен + образец К" 2>&1 | grep -a "mp3\|Error\|Traceback" >> "$LOG"
.venv/bin/python "$T/paragraph_11b.py" "$F" main "$R (F5, обучен)" "Герасимов - обучен + образец К + чистка DFN" 2>&1 | grep -a "mp3\|Error\|Traceback" >> "$LOG"
cp "$V3/Герасимов - F5 как сейчас (образец К).mp3" "$D/Герасимов - F5 как сейчас (образец К).mp3"
cp "$V3/Герасимов - проба Олеся + образец К + чистка DFN.mp3" "$D/Герасимов - проба (45 мин) + образец К + чистка DFN.mp3"
cp "$V3/Герасимов - живой (Олеся, 30-я минута).mp3" "$D/Герасимов - живой (Олеся, 30-я минута).mp3"
.venv/bin/python "$T/measure_11b.py" "точка Д" "$R" "Архив/11б/абзац.txt" \
  "$D/Герасимов - F5 как сейчас (образец К).mp3=F5 как сейчас (К)" \
  "$D/Герасимов - проба (45 мин) + образец К + чистка DFN.mp3=проба + К + DFN" \
  "$D/Герасимов - обучен + образец Олеся.mp3=обучен + Олеся" \
  "$D/Герасимов - обучен + образец К.mp3=обучен + К" \
  "$D/Герасимов - обучен + образец К + чистка DFN.mp3=обучен + К + DFN" 2>&1 | grep -a '^{' >> "$LOG"

say "длинный кусок"
.venv/bin/python "$T/long_piece_39.py" f5обучен "$R (F5, обучен, образец Олеся)=Герасимов (F5, обучен, образец Олеся)" \
  "$R (F5, обучен, образец К)=Герасимов (F5, обучен, образец К)" "$R (F5, обучен)=Герасимов (F5, обучен, образец К + DFN)" \
  2>&1 | grep -a "обучен\|Error\|Traceback" >> "$LOG"
.venv/bin/python "$T/measure_11b.py" "длинный кусок" "$R" "Архив/голоса диктора 3.9/длинный кусок/Глава первая (отрывок).txt" \
  "$L/Старая сборка F5/Герасимов (F5).mp3=F5 как сейчас (11а)" \
  "$L/Дообученный F5/Герасимов (F5, обучен, образец Олеся).mp3=обучен + Олеся" \
  "$L/Дообученный F5/Герасимов (F5, обучен, образец К).mp3=обучен + К" \
  "$L/Дообученный F5/Герасимов (F5, обучен, образец К + DFN).mp3=обучен + К + DFN" 2>&1 | grep -a '^{' >> "$LOG"

say "голос в программе: «$R (F5, обучен)» - образец К + DFN"
for v in "$R (F5, обучен, образец Олеся)" "$R (F5, обучен, образец К)"; do
  .venv/bin/python "$T/install_f5_trained_11b.py" --remove "$v" >> "$LOG"
done

say "тесты ударений: текст"
.venv/bin/python "$T/test_stress.py" 2>&1 | grep -a "OK\|ПЛОХО\|Error\|Traceback" >> "$LOG"
.venv/bin/python "$T/stress_steps_11a.py" qwen3:14b итог 2>&1 | grep -av "^warn\|Warning" | tail -25 >> "$LOG"
say "тесты ударений: 50 трудных слов по звуку, F5"
.venv/bin/python "$T/stress50_f5_11b.py" "Игорь Ященко" "Игорь Ященко (F5, обучен)" "$R" "$R (F5, обучен)" \
  2>&1 | grep -a "разметка\|верно\|Error\|Traceback" >> "$LOG"
say "готово"
