"""Herald — ядро приложения: чтение книг, подготовка текста, синтез, сборка."""

APP_NAME = "Herald"
APP_TAGLINE = "книги, прочитанные вслух"
VERSION = "2.1"

ABOUT = """Herald {v} — {tag}

Превращает книгу в аудиокнигу прямо на этом компьютере: без интернета (кроме
разовой загрузки моделей), без подписок, ничего никуда не отправляется.

ЧТО УМЕЕТ
  • Читает txt, md, docx, epub, fb2, pdf (текстовый слой; сканы пропускает).
  • Разворачивает числа и сокращения в слова: «1990» -> «одна тысяча…».
  • Сама расставляет ударения (RUAccent), чтобы не было «зáмок» вместо «замóк».
  • Режет книгу на файлы примерно заданной длины и выдаёт их по порядку —
    первые можно слушать, пока считаются остальные.

ГОЛОС
  Основной движок — F5-TTS, русская модель Misha24-10/F5-TTS_RUSSIAN
  (вариант accent_tune, ~1,3 ГБ), работает нативно на видеоядре Apple через MLX.
  Голос не выбирается из списка готовых: он КЛОНИРУЕТСЯ по образцу. Даёшь любую
  запись нужного диктора — программа сама находит в ней кусок беглой речи на
  8-12 секунд, расшифровывает его (Whisper large-v3-turbo) и дальше читает
  книгу этим голосом.
  Запасной движок — системный голос macOS: мгновенный, но готовый, не клон.

ЯЗЫКИ
  Русский и английский. Язык книги определяется сам по тексту, и под него
  берётся своя модель: русская Misha24-10 (с ударениями через RUAccent) или
  английская lucasnewman/f5-tts-mlx. Голоса у языков раздельные — английскую
  книгу надо озвучивать образцом англоязычного диктора.

КАК СЧИТАЕТ
  Модель не «проговаривает» текст слово за словом, а сразу рисует звуковую
  картинку целого куска и потом несколько раз её уточняет. Число уточнений и
  есть «качество/скорость» в окне: 7 проходов против 16 дают вдвое меньше
  времени при той же разборчивости (расписание шагов из работы Fast F5-TTS).

СКОРОСТЬ на Apple M4
  Около 0,7 секунды расчёта на секунду звука — час книги примерно за 45 минут.
  Системный голос macOS — раз в двадцать быстрее, но звучит проще.

ГДЕ ЧТО ЛЕЖИТ
  Готовые голоса: ~/.cache/text2audio/voices/ (кнопка ниже открывает папку).
  Каждый голос — пара файлов: .wav с образцом и .txt с его расшифровкой.
  Модели: ~/.cache/huggingface/
  Результат: папка с именем книги рядом с самой книгой.
""".format(v=VERSION, tag=APP_TAGLINE)
