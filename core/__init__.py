"""Herald - ядро приложения: чтение книг, подготовка текста, синтез, сборка."""

APP_NAME = "Herald"
APP_TAGLINE = "книги, прочитанные вслух"
VERSION = "3.4"

ABOUT = """Herald {v} - {tag}

Превращает книгу в аудиокнигу прямо на этом компьютере: без интернета (кроме
разовой загрузки моделей), без подписок, ничего никуда не отправляется.

ЧТО УМЕЕТ
  • Читает txt, md, docx, epub, fb2, pdf (текстовый слой; сканы пропускает).
  • Разворачивает числа, даты, века, единицы и сокращения в слова с верным
    падежом: «везла 1250 руб.» -> «везла одну тысячу двести пятьдесят рублей»,
    «МГУ» -> «эм-гэ-у», «А. П. Чехов» -> «А. Пэ. Чехов» (ru-normalizr).
  • Сама расставляет ударения: RUAccent, а в омографах (зáмок / замóк) -
    silero-stress. Имя героя звучит одинаково во всей книге.
  • Режет книгу на части примерно заданной длины и выдаёт их по порядку -
    первые можно слушать прямо в окне (мини-плеер), пока считаются
    остальные. Пауза, «Продолжить озвучку» после остановки или сбоя, Mac не
    засыпает посреди книги.
  • Паузы настраиваются: после предложения, после абзаца и между репликами
    диалога (по умолчанию 0,4 / 0,8 / 1,1 с).
  • Окончания слов на концах кусков не теряются: в конец каждого куска модели
    задаётся известная тишина, и слово успевает договориться; последнее слово
    проверяется по последним буквам и при сбое переозвучивается.

ГОЛОС
  Голос КЛОНИРУЕТСЯ по образцу: даёшь любую запись нужного диктора (лучше
  аудиокнигу, связную прозу) - программа сама находит в ней чистый отрывок на
  7-12 секунд, расшифровывает его (Whisper large-v3-turbo) и дальше читает книгу
  этим голосом. Стихи, перечисления, неуверенно распознанные куски, записи с
  обрезанным верхом и срезанными вершинами волны в образец не берутся (только
  при автоматическом отборе: голос, выбранный на слух, не перепроверяется).
  Есть и готовые голоса Silero - без клонирования, очень быстрые.

ДВИЖКИ (выбраны слепым прослушиванием, Настройки)
  Основной - F5-TTS, русская модель Misha24-10 accent_tune, 12 шагов.
  ESpeech-TTS-1 - почти так же хорош, лицензия Apache-2.0. Черновик - быстрее,
  но с шумом. Silero v5 - готовые голоса (лицензия некоммерческая).
  Английский - модель lucasnewman/f5-tts-mlx.
  Чем считать, программа решает сама: Mac на Apple Silicon - видеоядро (MLX);
  Windows и Linux - видеокарта NVIDIA (отдельная докачка в Настройках) или
  процессор. Алгоритм везде один - звук тот же.

ПРОВЕРКА
  Каждый кусок распознаётся: съеденное окончание, пропавшее или неразборчивое
  слово - кусок пересчитывается. Строгую проверку всего куска можно выключить
  (быстрее примерно в полтора раза).

СКОРОСТЬ
  Apple M4: час звука - около 1 ч 20 мин счёта (со строгой проверкой - около
  2 ч): книгу удобно ставить на ночь. Видеокарта NVIDIA - сопоставимо (не
  проверено). Процессор - сутки и больше на книгу; там быстры голоса Silero.

ГДЕ ЧТО ЛЕЖИТ
  Голоса: ~/.cache/text2audio/voices/ (.wav образец, .txt расшифровка,
  .src.json - из какой записи сделан).
  Журнал проблем: ~/Library/Logs/Herald/herald.log (Windows:
  %LOCALAPPDATA%/Herald/Logs, Linux: ~/.local/state/Herald/log)
  Модели: ~/.cache/huggingface/
  Результат: папка с именем книги рядом с самой книгой.
""".format(v=VERSION, tag=APP_TAGLINE)
