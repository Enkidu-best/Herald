"""Движок озвучки: какие веса F5 и сколько шагов (NFE) на каждый кусок.

Основной движок - F5 Misha24-10 accent_tune на 16 шагах (B16): выбран слепым
прослушиванием главы 14.10 (вариант «С»: «всё отлично - произношение, звук,
ударения, диалоги»). Запасной - ESpeech-TTS-1 RL-V2 (C16, вариант «Ф»): чуть
больше шума или металла, зато свободная лицензия Apache-2.0. Qwen3-TTS и
Chatterbox в программу не вошли.

Шаги - это число уточнений «картинки звука». Меньше шагов - быстрее, но с шумом
и металлом (7 шагов в слепом прослушивании проиграли). 32 шага в окно не
выведены: в слепом сравнении они были хуже 16 и съедали окончания. Расписание
EPSS - прореженные шаги из Fast F5-TTS (arXiv 2505.19931).

Готовые голоса Silero - не пресет качества: их выбирают в списке голосов, и
тогда движок Silero включается сам.

rtf - сколько секунд счёта уходит на секунду звука на Apple M4 (замер на
отрывке главы, см. docs/Приёмка 3.0). По нему окно заранее говорит, сколько
ждать; во время озвучки окно показывает настоящий, замеренный RTF и запоминает
его для следующего прогноза.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Profile:
    key: str
    title: str
    engine: str
    kwargs: dict = field(default_factory=dict)
    rtf: float = 1.0
    hint: str = ""
    clone: bool = True


PROFILES: dict[str, Profile] = {p.key: p for p in (
    Profile("main", "Основной (16 шагов, рекомендуется)", "f5mlx",
            {"steps": 16, "schedule": "epss"}, rtf=2.3,
            hint="Лучший по слуху голос (вариант «С» слепого сравнения). Час звука - "
                 "около 2 ч 20 мин счёта: книгу удобно ставить на ночь."),
    Profile("espeech", "ESpeech (запасной, свободная лицензия)", "f5mlx",
            {"steps": 16, "schedule": "epss", "variant": "espeech"}, rtf=1.85,
            hint="Вариант «Ф» слепого сравнения: почти так же хорош, чуть больше шума "
                 "или металла, немного быстрее. Лицензия Apache-2.0 - можно и для "
                 "продукта. Первый запуск скачивает 2,7 ГБ."),
    Profile("draft", "Черновик (7 шагов)", "f5mlx",
            {"steps": 7, "schedule": "epss"}, rtf=1.05,
            hint="Вдвое быстрее, но с шумом и металлическим призвуком. "
                 "Для проверки текста и ударений, не для прослушивания."),
)}
DEFAULT_PROFILE = "main"
# Готовые голоса Silero: включаются выбором голоса, не пресетом
SILERO = Profile("silero", "Готовые голоса Silero", "silero", {}, rtf=0.03, clone=False)


def get(key: str | None) -> Profile:
    return PROFILES.get(key or DEFAULT_PROFILE, PROFILES[DEFAULT_PROFILE])
