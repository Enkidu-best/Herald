"""Движок озвучки: какие веса F5 и сколько шагов (NFE) на каждый кусок.

Основной движок - F5 Misha24-10 accent_tune: выбран слепым прослушиванием главы
14.10 (вариант «С»). С 3.2 - на 12 шагах: в слепой паре 16 против 12 (15.10)
Андрей выбрал 12 («восклицания без крика, некоторые слова лучше»), счёт на
25 % быстрее. Запасной - ESpeech-TTS-1 RL-V2 (вариант «Ф»): чуть больше шума
или металла, зато свободная лицензия Apache-2.0; с 3.3 тоже на 12 шагах (пара
12/16 вслепую 15.10: «почти одинаково», на 16 «чуть-чуть металла»). Qwen3-TTS и
Chatterbox в программу не вошли.
В окне названия без цифр - число шагов пользователю ничего не говорит.

Шаги - это число уточнений «картинки звука». Меньше шагов - быстрее, но с шумом
и металлом (7 шагов в слепом прослушивании проиграли). 32 шага в окно не
выведены: в слепом сравнении они были хуже 16 и съедали окончания. Расписание
EPSS - прореженные шаги из Fast F5-TTS (arXiv 2505.19931).

Готовые голоса Silero - не пресет качества: их выбирают в списке голосов, и
тогда движок Silero включается сам.

rtf - сколько секунд счёта уходит на секунду звука на Apple M4 (замер на
отрывке главы, см. docs/Приёмка 3.1). По нему окно заранее говорит, сколько
ждать; во время озвучки окно показывает настоящий, замеренный RTF и запоминает
его для следующего прогноза.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Profile:
    key: str
    title: str
    engine: str
    kwargs: dict = field(default_factory=dict)
    rtf: float = 1.0
    hint: str = ""
    clone: bool = True


PROFILES: dict[str, Profile] = {p.key: p for p in (
    Profile("main", "Основной (рекомендуется)", "f5mlx",
            {"steps": 12, "schedule": "epss"}, rtf=1.4,
            hint="Лучший по слуху голос. Час звука - около 1 ч 25 мин счёта с "
                 "проверкой слов по звуку: книгу удобно ставить на ночь."),
    Profile("espeech", "ESpeech (свободная лицензия)", "f5mlx",
            {"steps": 12, "schedule": "epss", "variant": "espeech"}, rtf=1.4,
            hint="Почти так же хорош, чуть больше шума или металла. Лицензия "
                 "Apache-2.0 - можно и для продукта. Первый запуск скачивает 2,7 ГБ."),
    Profile("draft", "Черновик", "f5mlx",
            {"steps": 7, "schedule": "epss"}, rtf=0.85,
            hint="Быстрее, но с шумом и металлическим призвуком. Для проверки текста "
                 "и ударений, не для прослушивания."),
)}
DEFAULT_PROFILE = "main"
# Готовые голоса Silero: включаются выбором голоса, не пресетом
SILERO = Profile("silero", "Готовые голоса Silero", "silero", {}, rtf=0.03, clone=False)


# Во сколько раз медленнее, чем на Apple M4 (MLX), на других вычислителях.
# cpu - замер на раннерах GitHub (4 ядра): клон F5 RTF 15-22 вместе с загрузкой
# моделей, см. docs/Приёмка 3.2; cuda - оценка:
# на видеокарте NVIDIA класса RTX 3060 F5 считает примерно как M4 (не проверено -
# на раннерах и у нас видеокарты нет). Окно показывает прогноз по этим числам,
# а после первой части - по настоящему замеру.
ACCEL_MUL = {"mlx": 1.0, "cuda": 1.0, "cpu": 12.0}
ACCEL_TITLE = {"mlx": "видеоядро Apple (MLX)", "cuda": "видеокарта NVIDIA",
               "cpu": "процессор - очень медленно"}


@dataclass(frozen=True)
class Quality:
    """Качество / скорость (3.6): на скольких из 12 шагов идёт подсказка CFG.

    На каждом шаге модель считается дважды - с текстом и без, разница усиливает
    следование тексту. На поздних шагах второй проход можно опустить: звук чуть
    менее чистый, счёт быстрее (слепое сравнение 3.5: разница небольшая,
    Андрей выбрал скорость). Модель и 12 шагов не меняются.
    """
    key: str
    title: str
    cfg_steps: int | None          # None - на всех шагах, как в F5
    rtf_mul: float                 # во сколько раз быстрее «Максимального качества»
    hint: str = ""


QUALITY: dict[str, Quality] = {q.key: q for q in (
    Quality("fast", "Быстрее", 4, 0.64,
            "Подсказка на 4 шагах из 12: книга считается быстрее, чем звучит. "
            "На слух чуть меньше чистоты."),
    Quality("balanced", "Сбалансировано (рекомендуется)", 6, 0.75,
            "Подсказка на 6 шагах из 12: счёт примерно как длина звука, на слух "
            "почти не отличить от максимального качества."),
    Quality("max", "Максимальное качество", None, 1.0,
            "Подсказка на всех 12 шагах, как в 3.5: чище всего, счёт дольше звука "
            "в 1,4 раза."),
)}
DEFAULT_QUALITY = "balanced"


def quality(key: str | None) -> Quality:
    return QUALITY.get(key or DEFAULT_QUALITY, QUALITY[DEFAULT_QUALITY])


def engine_kwargs(p: Profile, quality_key: str | None = None) -> dict:
    """Параметры движка профиля с учётом режима «Качество / скорость».
    Режим действует на клоны с 12 шагами (основной, ESpeech); черновик - как есть."""
    kw = dict(p.kwargs)
    q = quality(quality_key)
    if p.clone and kw.get("steps") == 12 and q.cfg_steps is not None:
        kw["cfg_steps"] = q.cfg_steps
    return kw


def rtf_for(p: Profile, accel: str, quality_key: str | None = None) -> float:
    mul = quality(quality_key).rtf_mul if p.clone and p.kwargs.get("steps") == 12 else 1.0
    return p.rtf * mul * ACCEL_MUL.get(accel, 1.0)


def get(key: str | None) -> Profile:
    return PROFILES.get(key or DEFAULT_PROFILE, PROFILES[DEFAULT_PROFILE])
